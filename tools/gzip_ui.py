# PlatformIO pre-build script: gzips the HTML in src/web_ui.h into
# src/web_ui_gz.h so the page is sent compressed (~4x smaller), which matters
# on the ESP32-C3's low-power, BLE-shared WiFi link.
#
# Edit src/web_ui.h as normal; web_ui_gz.h is regenerated on every build.
import gzip
import os
import re

Import("env")  # noqa: F821  (provided by PlatformIO/SCons)

src_dir = env.subst("$PROJECT_SRC_DIR")  # noqa: F821
src = os.path.join(src_dir, "web_ui.h")
dst = os.path.join(src_dir, "web_ui_gz.h")

with open(src, "r", encoding="utf-8") as f:
    text = f.read()

m = re.search(r'R"rawhtml\((.*)\)rawhtml"', text, re.S)
if not m:
    raise SystemExit("gzip_ui.py: PAGE_HTML raw string not found in web_ui.h")

data = gzip.compress(m.group(1).encode("utf-8"), compresslevel=9, mtime=0)

lines = []
for i in range(0, len(data), 20):
    lines.append("  " + ",".join("0x%02x" % b for b in data[i:i + 20]) + ",")

out = (
    "// GENERATED by tools/gzip_ui.py from web_ui.h — do not edit.\n"
    "#pragma once\n"
    "#include <pgmspace.h>\n\n"
    "const size_t PAGE_GZ_LEN = %d;\n"
    "const uint8_t PAGE_GZ[] PROGMEM = {\n%s\n};\n" % (len(data), "\n".join(lines))
)

old = None
if os.path.exists(dst):
    with open(dst, "r", encoding="utf-8") as f:
        old = f.read()
if out != old:  # only touch the file when the page changed, to avoid rebuilds
    with open(dst, "w", encoding="utf-8") as f:
        f.write(out)

print("gzip_ui.py: web page %d -> %d bytes gzipped" % (len(m.group(1)), len(data)))
